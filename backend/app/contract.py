"""Snapshot of the API contract for the frontend parity test (contract §3.2-9).

`build()` returns, keyed by the TypeScript name used in `frontend/src/types/api.ts`, JSON Schemas
generated by Pydantic with one shared `$defs` table:
- `responses`: every response model (serialization mode);
- `requests`: every request body (validation mode);
- `queries`: the query-parameter model of each §8 endpoint (`*Params` in TypeScript; validation mode,
  compared like request bodies). Multi-value filters are lists there and comma-separated on the wire;
- `envelopes`: the error envelope of every non-2xx response and the `Paginated<T>` instantiation of each
  paginated endpoint (serialization mode, compared like responses);
- `error_codes`: every error code the backend can return (all `AppError` subclasses);
- `field_error_codes`: every code a 422's `details.field_codes` can carry, with the names of its
  parameters (`app.core.field_errors`, B10-18).

`QUERY_ROUTES` names the query model of every §8 endpoint that takes query parameters; a test checks
that each implemented route declares exactly that model's parameters.

The committed copy is `frontend/src/types/backend-contract.json`; `frontend/src/types/api.contract.test.ts`
compares `api.ts` against it, and `tests/unit/test_contract_snapshot.py` fails when it is stale.
Regenerate it after changing a schema or an error code:

    npm run contract:snapshot                      (from frontend/)
    python -m app.contract --out ../frontend/src/types/backend-contract.json   (from backend/)
"""

